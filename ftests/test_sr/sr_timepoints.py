class TimepointModelTestCase(unittest.TestCase):
	def test_timepoint_of_a_document_from_each_cached_source(self):
		doc = fixture('timepoint-length')
		series = dcmsr_local_series([doc])
		instance = series.instances_collection[0]
		self.assertEqual((instance.timepoint, series.timepoint), (POSTOP, POSTOP))			# cached file
		self.assertEqual(instance.report.parsed.timepoint, POSTOP)							# parsed report
		self.assertEqual((instance.timepoint, series.timepoint), (POSTOP, POSTOP))
		instance._report, instance._dcmfile, instance._tags = None, None, simplified(doc)	# cached tags
		self.assertEqual((instance.get_timepoint(diagnostics=[], strict=True), series.get_timepoint(strict=True)), (POSTOP, POSTOP))
		none = dcmsr_local_series([fixture('timepoint-length-none')])
		self.assertIsNone(none.timepoint)
		self.assertIsNone(none.instances_collection[0].timepoint)

	def test_membership_is_not_cached(self):
		series = dcmsr_local_series([copy.deepcopy(fixture('timepoint-length'))])
		self.assertEqual(series.timepoint, POSTOP)
		dcm_set_timepoint(series.instances_collection[0]._dcmfile, PREOP, replace=True)
		self.assertEqual(series.timepoint, PREOP)

	def test_series_that_joins_a_timepoint(self):
		series = dcmsr_local_series([fixture('timepoint-join-r1'), fixture('timepoint-join-r2')])
		diagnostics = []
		self.assertEqual(series.get_timepoint(diagnostics=diagnostics, strict=True), POSTOP)
		self.assertEqual(diagnostics, [])
		first, second = sorted(series.instances_collection, key=lambda dcm: str(dcm.ts))
		self.assertEqual((first.timepoint, second.timepoint), (None, POSTOP))
		measurements = [m for by_type in series.measurements(all_revisions=True).values() for c in by_type.values() for m in c]
		self.assertEqual(len(measurements), 2)
		self.assertEqual(sorted(str(m.timepoint) for m in measurements), sorted([str(None), str(POSTOP)]))
		self.assertEqual([m.timepoint for m in measurements if m.sr_instance is first], [None])

	def test_series_with_conflicting_revisions(self):
		series = dcmsr_local_series([fixture('timepoint-conflict-r1'), fixture('timepoint-conflict-r2')])
		diagnostics = []
		for _ in range(3):
			self.assertEqual(series.get_timepoint(diagnostics=diagnostics).uid, PREOP.uid)
		conflicts = [d for d in diagnostics if d.condition == SR_CONDITION_TIMEPOINT_SERIES_CONFLICT]
		self.assertEqual(len(conflicts), 1)
		self.assertEqual((conflicts[0].severity, conflicts[0].path), ('warning', 'series %s' % series.pk))
		with self.assertRaises(SRDiagnosticError):
			series.get_timepoint(strict=True)
		self.assertEqual(series.timepoint.uid, PREOP.uid)

	def test_a_revision_with_nothing_cached_is_not_requested_for_the_conflict_check(self):
		series = dcmsr_local_series([fixture('timepoint-conflict-r1'), fixture('timepoint-conflict-r2')])
		first, second = sorted(series.instances_collection, key=lambda dcm: str(dcm.ts))
		first._dcmfile = None			# a request for it would fail: the local series has no imaging server
		diagnostics = []
		self.assertEqual(series.get_timepoint(diagnostics=diagnostics).uid, PREOP.uid)
		self.assertEqual([d.condition for d in diagnostics], [SR_CONDITION_PREDECESSOR_CHAIN_UNVERIFIED])
		self.assertIsNone(first.__dict__.get('_tags'))

	def test_membership_follows_the_current_document_with_and_without_the_files(self):
		docs = [fixture('timepoint-join-r1'), fixture('timepoint-join-r2')]
		series = dcmsr_local_series(docs)
		instances = list(series.instances_collection)
		for instance, doc in zip(instances, docs):
			instance._dcmfile, instance._tags = None, simplified(doc)		# indexed headers only
		diagnostics = []
		current = series.instances_collection.current_instance()
		self.assertEqual(series.get_timepoint(diagnostics=diagnostics), current.timepoint)
		self.assertEqual(series.get_timepoint(), POSTOP)
		self.assertEqual([d.condition for d in diagnostics], [SR_CONDITION_PREDECESSOR_CHAIN_UNVERIFIED])
		for instance, doc in zip(instances, docs):
			instance._dcmfile = doc											# every file cached
		diagnostics = []
		self.assertEqual(series.get_timepoint(diagnostics=diagnostics), POSTOP)
		self.assertEqual(diagnostics, [])
		self.assertIs(series.instances_collection.current_instance(), current)

	def study(self, *topics):
		return collection_of(*[dcmsr_local_series([fixture(topic)]) for topic in topics])

	def test_timepoints_of_a_study(self):
		for topics in (('timepoint-study-a', 'timepoint-study-b', 'timepoint-study-none'),
				('timepoint-study-none', 'timepoint-study-b', 'timepoint-study-a')):
			collection = self.study(*topics)
			found = collection.timepoints(strict=True)
