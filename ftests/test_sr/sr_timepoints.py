def fixture(topic):
	return pydicom.dcmread(os.path.join(T.FIXTURES_DIR, T.fixture_name(topic)))


def mirror_of(ds):
	return OrderedDict((name, ds.get(name)) for name in DCMHEADER_TIMEPOINT_MIRROR if name in ds)


def foreign_item():
	return T.mpps_image_dataset().ReferencedPerformedProcedureStepSequence[0]


def with_foreign(ds, own=OWN):
	'''	The document with a Modality Performed Procedure Step item before its other items and series-level values of
		its own in place of any copy '''
	ds = copy.deepcopy(ds)
	ds.ReferencedPerformedProcedureStepSequence = Sequence([foreign_item()] + list(ds.get(SEQUENCE) or []))
	for name in DCMHEADER_TIMEPOINT_MIRROR:
		if name in ds:
			delattr(ds, name)
	for name, value in own.items():
		setattr(ds, name, value)
	return ds


def resave(model, name, **kwargs):
	return T.write(model, name, series=False, **kwargs)


def simplified(ds):
	'''	Simplified tags of a dataset, as an imaging server serves them: values as text by keyword, a sequence as a
		list of mappings '''
	found = OrderedDict()
	for elem in ds:
		if not elem.keyword or elem.keyword == 'PixelData':
			continue
		found[elem.keyword] = [simplified(item) for item in elem.value] if elem.VR == 'SQ' else str(elem.value)
	return found


def tracking(results):
	'''	Tracking UIDs of every annotation in a result of the findings API, whatever its shape '''
	if isinstance(results, dict):
		return sorted(uid for value in results.values() for uid in tracking(value))
	return sorted(str(item.tracking_uid) for item in results)


def annotated(name, timepoint=None, series=None):
	'''	A document with a Series Tag, a Length and a landmark set on the synthetic image.

		@returns (pydicom.Dataset, dict): the document and the tracking UIDs of its `finding`, `length` and `landmarks`
	'''
	uids = dict((kind, T._uid('%s/%s' % (name, kind))) for kind in ('finding', 'length', 'landmarks'))
	model = T.report(timepoint, tracking_uid=uids['length'])
	model.findings = [Finding.series_tag(TAG_REJECT, reference=ImageReference(T.MR_IMAGE_STORAGE, T.IMAGE_SOP_UID, None, T.IMAGE_SERIES_UID),
		tracking_uid=uids['finding'])]
	lset = LandmarkSet.from_points([(1.0, 2.0, 3.0)], name='Points of ' + name, frame_of_reference_uid=T.IMAGE_FOR,
		fiducial_uids=[T._uid(name + '/fiducial')])
	lset.tracking_uid = uids['landmarks']
	model.landmarks = [lset]
	return T.write(model, name, series=series), uids


def collection_of(*series):
	collection = DcmSRSeriesCollection(None, [])
	collection.extend(series)
	return collection


class TimepointDocumentTestCase(unittest.TestCase):
	def test_parsed_document_keeps_its_trailing_defaults(self):
		self.assertEqual(SRParsedDocument._fields[-1], 'timepoint')
		parsed = SRParsedDocument(*([None] * (len(SRParsedDocument._fields) - 3)))
		self.assertEqual((parsed.frame_records, parsed.point_collections, parsed.timepoint), (None, (), None))

	def test_new_document_without_a_timepoint_is_unchanged(self):
		plain = T.write(T.report(tracking_uid='2.25.1'), 'plain')
		self.assertIn(SEQUENCE, plain)
		self.assertEqual(len(plain.ReferencedPerformedProcedureStepSequence), 0)
		self.assertEqual(mirror_of(plain), {})
		# A document written with a timepoint differs from it by the timepoint item and its copy only
		stamped = T.write(T.report(POSTOP, tracking_uid='2.25.1'), 'plain')
		self.assertNotEqual(stamped, plain)
		self.assertEqual(dcm_remove_timepoint(stamped, mirror=True), plain)

	def test_new_document_with_a_timepoint(self):
		model = T.report(tracking_uid='2.25.1')
		self.assertIsNone(model.timepoint)
		model.timepoint = POSTOP
		doc = T.write(model, 'stamped')
		self.assertEqual(len(doc.ReferencedPerformedProcedureStepSequence), 1)
		self.assertEqual(dcm_timepoint(doc), POSTOP)
		self.assertEqual(list(mirror_of(doc).values()), [POSTOP.id, POSTOP.date, POSTOP.time, POSTOP.description])
		self.assertEqual(T.read(doc).parsed.timepoint, POSTOP)
		self.assertEqual(T.read(doc).timepoint, POSTOP)

	def test_a_value_that_is_not_a_timepoint_or_fails_its_check_is_refused_before_the_write(self):
		for value in (tuple(POSTOP), POSTOP.uid, POSTOP._replace(description='x' * 65), POSTOP._replace(id='x' * 17)):
			model = T.report(value, tracking_uid='2.25.1')
			with self.assertRaises(ValueError):
				T.write(model, 'refused')
			self.assertIsNone(model.__dict__.get('_sr'))			# nothing was built

	def test_resave_keeps_the_item_and_the_copy(self):
		first = fixture('timepoint-length')
		second = resave(T.read(first), 'resave-1')
		third = resave(T.read(second), 'resave-2')
		for doc in (second, third):
			self.assertEqual(doc.SeriesInstanceUID, first.SeriesInstanceUID)
			self.assertEqual(list(doc.ReferencedPerformedProcedureStepSequence), list(first.ReferencedPerformedProcedureStepSequence))
			self.assertEqual(mirror_of(doc), mirror_of(first))
		# A document written without the copy is re-saved without it
		bare = copy.deepcopy(first)
		for name in DCMHEADER_TIMEPOINT_MIRROR:
			delattr(bare, name)
		again = resave(T.read(bare), 'resave-3')
		self.assertEqual((dcm_timepoint(again), mirror_of(again)), (POSTOP, {}))

	def test_resave_without_a_timepoint_is_unchanged(self):
		first = fixture('timepoint-length-none')
		second = resave(T.read(first), 'resave-none')
		self.assertEqual(len(second.ReferencedPerformedProcedureStepSequence), 0)
		self.assertEqual(mirror_of(second), {})
		self.assertIsNone(T.read(second).timepoint)

	def test_resave_keeps_other_items_and_series_level_values(self):
		for topic, expected in (('timepoint-length', POSTOP), ('timepoint-length-none', None)):
			source = with_foreign(fixture(topic))
			doc = resave(T.read(source), 'foreign-' + topic)
			items = list(doc.ReferencedPerformedProcedureStepSequence)
			self.assertEqual(items[0], foreign_item())
			self.assertEqual(items[0].InstanceNumber, 7)
			self.assertEqual(len(items), 2 if expected else 1)
			self.assertEqual(dcm_timepoint(doc), expected)
			self.assertEqual(mirror_of(doc), OWN)

	def test_values_read_over_the_limits_are_written_back_and_assigned_ones_are_checked(self):
		long_description = 'A description read from a document that is longer than sixty-four chars'
		self.assertEqual(len(long_description), 71)
		source = copy.deepcopy(fixture('timepoint-length'))
		T._set_item(source, PerformedProcedureStepDescription=long_description)
		held = POSTOP._replace(description=long_description)

		model = T.read(source)
		self.assertEqual(model.timepoint, held)
		self.assertEqual(dcm_timepoint(resave(model, 'long-1')), held)

		model = T.read(source)
		model.timepoint = Timepoint(*held)			# an equal value
		self.assertEqual(dcm_timepoint(resave(model, 'long-2')), held)

		for changed in (held._replace(description=long_description + '!'), held._replace(id='TP-CHANGED')):
			model = T.read(source)
			model.timepoint = changed
			with self.assertRaises(ValueError):
				resave(model, 'long-3')

	def test_joining_writes_into_the_same_series(self):
		first = fixture('timepoint-join-r1')
		model = T.read(first)
		self.assertIsNone(model.timepoint)
		model.timepoint = POSTOP
		second = resave(model, 'join')
		self.assertEqual(second.SeriesInstanceUID, first.SeriesInstanceUID)
		self.assertEqual(dcm_timepoint(second), POSTOP)
		self.assertEqual(list(mirror_of(second).values()), [POSTOP.id, POSTOP.date, POSTOP.time, POSTOP.description])
		# With series-level values of its own, the joined document keeps them and gets no copy
		model = T.read(with_foreign(first))
		model.timepoint = POSTOP
		joined = resave(model, 'join-own')
		self.assertEqual((dcm_timepoint(joined), mirror_of(joined)), (POSTOP, OWN))

	def test_the_timepoint_of_a_series_is_not_changed_or_cleared(self):
		first = fixture('timepoint-length')
		for value in (PREOP, None, POSTOP._replace(uid=PREOP.uid)):
			model = T.read(first)
			model.timepoint = value
			with self.assertRaises(ValueError):
				resave(model, 'refused')
			with self.assertRaises(ValueError):
				T.write(model, 'refused', dcmsr_series_uid=str(first.SeriesInstanceUID))
			moved = T.write(model, 'moved', series='another')
			self.assertNotEqual(moved.SeriesInstanceUID, first.SeriesInstanceUID)
			self.assertEqual(dcm_timepoint(moved), value)
		# The same timepoint with other descriptive values is the same timepoint
		model = T.read(first)
		model.timepoint = POSTOP_LATER
		self.assertEqual(dcm_timepoint(resave(model, 'same-uid')), POSTOP_LATER)

	def test_a_model_bound_to_a_series_is_compared_with_the_series(self):
		series = dcmsr_local_series([fixture('timepoint-length')])
		for value, refused in ((PREOP, True), (None, True), (POSTOP, False)):
			model = T.report(value, tracking_uid='2.25.1')
			model.series = series
			if refused:
				with self.assertRaises(ValueError):
					T.write(model, 'bound', series=False)
			else:
				doc = T.write(model, 'bound', series=False)
				self.assertEqual((str(doc.SeriesInstanceUID), dcm_timepoint(doc)), (series.series_uid, POSTOP))
		# A series without a timepoint is joined
		model = T.report(PREOP, tracking_uid='2.25.1')
		model.series = dcmsr_local_series([fixture('timepoint-length-none')])
		self.assertEqual(dcm_timepoint(T.write(model, 'bound-join', series=False)), PREOP)

	def bound(self, source_topic, *topics):
		'''	A model parsed from one revision and bound to the local series of all the revisions given '''
		model = T.read(fixture(source_topic))
		model.series = dcmsr_local_series([fixture(topic) for topic in topics])
		return model

	def test_an_older_revision_cannot_clear_or_move_the_series_it_is_bound_to(self):
		# The first revision has no timepoint; the series joined one in its second revision
		topics = ('timepoint-join-r1', 'timepoint-join-r2')
		self.assertEqual(self.bound(*((topics[0],) + topics)).series.timepoint, POSTOP)
		for value in (None, PREOP):
			model = self.bound(topics[0], *topics)
			model.timepoint = value
			with self.assertRaises(ValueError):
				resave(model, 'stale')
			with self.assertRaises(ValueError):
				T.write(model, 'stale', dcmsr_series_uid=model.series.series_uid)
			self.assertIsNone(model.__dict__.get('_sr'))
			moved = T.write(model, 'stale-moved', series='another')
			self.assertEqual(dcm_timepoint(moved), value)
		model = self.bound(topics[0], *topics)
		model.timepoint = POSTOP
		kept = resave(model, 'stale-kept')
		self.assertEqual((str(kept.SeriesInstanceUID), dcm_timepoint(kept)), (model.series.series_uid, POSTOP))

	def test_an_older_revision_with_another_timepoint_is_checked_against_the_current_one(self):
		# The first revision carries one timepoint UID, the current document of the series another
		topics = ('timepoint-conflict-r1', 'timepoint-conflict-r2')
		current = dcm_timepoint(fixture(topics[1]))
		self.assertNotEqual(current.uid, POSTOP.uid)
		for value in (POSTOP, None, OTHER):			# the parsed document's own timepoint included
			model = self.bound(topics[0], *topics)
			model.timepoint = value
			with self.assertRaises(ValueError):
				resave(model, 'stale')
			self.assertEqual(dcm_timepoint(T.write(model, 'stale-moved', series='another')), value)
		model = self.bound(topics[0], *topics)
		model.timepoint = current
		self.assertEqual(dcm_timepoint(resave(model, 'stale-kept')), current)

	def test_the_parsed_document_decides_when_the_series_cannot_be_read_from_what_is_cached(self):
		topics = ('timepoint-conflict-r1', 'timepoint-conflict-r2')
		# Nothing cached for the current document: no request is made and the parsed document's timepoint applies
		model = self.bound(topics[0], *topics)
		for instance in model.series.instances_collection:
			instance._dcmfile = None
		self.assertEqual(model.series._cached_timepoint(), (False, None))
		self.assertEqual(dcm_timepoint(resave(model, 'fallback')), POSTOP)
		model.timepoint = PREOP
		with self.assertRaises(ValueError):
			resave(model, 'fallback')
		# A series whose instances are not populated
		model = self.bound(topics[0], *topics)
		model.series._instances = None
		self.assertEqual(model.series._cached_timepoint(), (False, None))
		self.assertEqual(dcm_timepoint(resave(model, 'fallback')), POSTOP)

	def test_a_destination_that_names_the_bound_series_is_checked(self):
		# A model read from one series and bound to another: writing into the bound series is checked against it
		model = T.read(fixture('timepoint-study-b'))
