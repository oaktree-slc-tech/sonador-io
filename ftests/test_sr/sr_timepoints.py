	def expected(self, kind, *names):
		return sorted(self.uids[name][kind] for name in names)

	def test_narrowing_by_timepoint(self):
		calls = (('finding', self.collection.findings), ('length', self.collection.measurements), ('landmarks', self.collection.landmarks))
		for kind, call in calls:
			self.assertEqual(tracking(call()), self.expected(kind, 'postop', 'preop', 'none'))
			self.assertEqual(tracking(call(timepoint_uid=POSTOP.uid)), self.expected(kind, 'postop'))
			self.assertEqual(tracking(call(timepoint_uid=PREOP.uid)), self.expected(kind, 'preop'))
			self.assertEqual(tracking(call(timepoint_uid=TIMEPOINT_DEFAULT)), self.expected(kind, 'none'))
			self.assertEqual(tracking(call(timepoint_uid=OTHER.uid)), [])

	def test_unknown_timepoint_gives_the_empty_result_of_each_shape(self):
		for call, empty in ((self.collection.findings, FindingCollection), (self.collection.measurements, MeasurementCollection)):
			full = call()
			series_uid = next(iter(full))
