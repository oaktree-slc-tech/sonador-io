	def test_series_level_values_in_another_series(self):
		full = OrderedDict((('PerformedProcedureStepID', 'OWN-ID'), ('PerformedProcedureStepStartDate', '20250101'),
			('PerformedProcedureStepStartTime', '010101'), ('PerformedProcedureStepDescription', 'OWN DESCRIPTION')))
		partial = OrderedDict((('PerformedProcedureStepDescription', 'OWN DESCRIPTION'),))
		empty = OrderedDict((('PerformedProcedureStepID', ''),))
		for own in (full, partial, empty):
			source = with_foreign(fixture('timepoint-length'), own=own)
			held = mirror_of(source)
			for value in (PREOP, None):
				model = T.read(source)
				model.timepoint = value
				moved = T.write(model, 'moved', series='another')
				self.assertEqual(dcm_timepoint(moved), value)
				self.assertEqual(mirror_of(moved), held)

				model = T.read(source)
				model.timepoint = value
				owned = T.write(model, 'owned', series='another', timepoint_mirror=True)
				self.assertEqual(dcm_timepoint(owned), value)
				self.assertEqual(list(mirror_of(owned).values()), [PREOP.id, PREOP.date, PREOP.time, PREOP.description] if value else [])
				self.assertEqual(owned.ReferencedPerformedProcedureStepSequence[0], foreign_item())

