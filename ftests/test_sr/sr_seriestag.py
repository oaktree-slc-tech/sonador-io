		x, y, z = '2.25.1', '2.25.2', '2.25.3'
		a1 = self.make_document([self.finding(TAG_REJECT, x), self.finding(TAG_METAL, y)], '2.25.500', '100000', sop_uid='2.25.5001')
		a2 = self.make_document([self.finding(TAG_REJECT, x)], '2.25.500', '110000', sop_uid='2.25.5002')
