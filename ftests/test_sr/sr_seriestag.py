# ---- content tree oracle: what a re-save may change ----

def canonical_code(code):
	'''	(value, designator, version) of a code, the value from any of the three attributes
	'''
	if code is None:
		return None
	version = code.get('CodingSchemeVersion')
	return (dcm_code_value(code), code.get('CodingSchemeDesignator'), str(version) if version else None)


def canonical_value(item):
	vt = item.get('ValueType')
	if vt == 'CODE':
		return ('CODE', canonical_code(item.ConceptCodeSequence[0]))
	if vt == 'TEXT':
		name = canonical_code(item.ConceptNameCodeSequence[0]) if 'ConceptNameCodeSequence' in item else None
		if name and name[0] in ROLE_CODES:
			# Colours are compared in 8-bit RGB with a tolerance of 1 per channel
			return ('COLOR', dcmlab2color(item.TextValue))
		return ('TEXT', str(item.TextValue))
	if vt == 'UIDREF':
		return ('UIDREF', str(item.UID))
	if vt == 'PNAME':
		return ('PNAME', str(item.PersonName))
	if vt == 'NUM':
		mv = item.MeasuredValueSequence[0]
		return ('NUM', float(mv.NumericValue), canonical_code(mv.MeasurementUnitsCodeSequence[0]))
	if vt == 'IMAGE':
		ref = item.ReferencedSOPSequence[0]
		return ('IMAGE', str(ref.ReferencedSOPClassUID), str(ref.ReferencedSOPInstanceUID), ref.get('ReferencedFrameNumber'))
	if vt == 'CONTAINER':
		return ('CONTAINER',)
	return (vt, str(item.get('TextValue') or item.get('UID') or ''))


class Node:
	'''	Canonical content item: relationship, value type, concept name, value and children
	'''
	def __init__(self, item):
		self.rel = item.get('RelationshipType')
		self.vt = item.get('ValueType')
		self.name = canonical_code(item.ConceptNameCodeSequence[0]) if item.get('ConceptNameCodeSequence') else None
		self.value = canonical_value(item)
		self.children = [Node(c) for c in (item.get('ContentSequence') or [])]

	def key(self):
		return (self.rel, self.vt, self.name, self.value if self.value[0] != 'COLOR' else ('COLOR',))

	def find(self, value):
		return [c for c in self.children if c.name and c.name[0] == value]


def compare_nodes(test, expected, actual, path='root'):
	'''	Assert content-tree equivalence: same multiset of children by key (order ignored), colours
		within tolerance, recursively
	'''
	test.assertEqual(expected.key(), actual.key(), path)
	if expected.value[0] == 'COLOR':
		for e, a in zip(expected.value[1], actual.value[1]):
			test.assertLessEqual(abs(e - a), 1, '%s colour %s vs %s' % (path, expected.value[1], actual.value[1]))
	test.assertEqual(Counter(c.key() for c in expected.children), Counter(c.key() for c in actual.children),
		'%s: children differ' % path)
	remaining = list(actual.children)
	for child in expected.children:
		match = next(c for c in remaining if c.key() == child.key())
		remaining.remove(match)
		compare_nodes(test, child, match, '%s / %s' % (path, child.name[0] if child.name else child.vt))


def expected_group(node, layout):
	'''	The source measurement group after the transformations a re-save is permitted to make: (a) missing
		relationship types filled, (b) SELECTED FROM -> INFERRED FROM, (c) version equal to the
		designator dropped, (d) Sonador-SR concepts carrying an undefined scheme version read at the
		registered one, (e) group-level properties moved under the
		Finding, (f) the display form of the writer's document class. Each transformation is recorded
		so that the caller can assert it happened.
	'''
	node = copy.deepcopy(node)
	applied = set()
	findings = node.find(DCMSR_FINDING.value)
	for finding in findings:
		if finding.rel is None:
			finding.rel = 'CONTAINS'; applied.add('a')
		value = finding.value[1]
		if value[2] and value[2] == value[1]:
			finding.value = ('CODE', (value[0], value[1], None)); applied.add('c')
		for child in finding.children:
			if child.vt == 'IMAGE':
				if child.rel is None:
					child.rel = 'INFERRED FROM'; applied.add('a')
				elif child.rel == 'SELECTED FROM':
					child.rel = 'INFERRED FROM'; applied.add('b')

	# Legacy group-level meta / display siblings belong to the single Finding
	if len(findings) == 1:
		finding = findings[0]
		moved = []
		for child in list(node.children):
			if child.name and (child.name[0] in META_CODES or child.name[0] == DCMSR_DISPLAY_ATTRIBUTES.value):
				node.children.remove(child)
				child.rel = 'HAS PROPERTIES'
				moved.append(child)
		if moved:
			finding.children.extend(moved); applied.add('e')

	def fix_versions(n):
		if n.name and n.name[1] == 'Sonador-SR' and n.name[2] and n.name[2] != SONADOR_SCHEME_VERSION_03:
			n.name = (n.name[0], n.name[1], SONADOR_SCHEME_VERSION_03); applied.add('d')
		for c in n.children:
			fix_versions(c)
	fix_versions(node)

	# Display form of the writer: flat (role items under the Finding) or nested (container)
	for finding in findings:
		container = next((c for c in finding.children if c.name and c.name[0] == DCMSR_DISPLAY_ATTRIBUTES.value), None)
		roles = [c for c in finding.children if c.name and c.name[0] in ROLE_CODES]
		if layout == DCMSR_LAYOUT_FLAT and container is not None:
			finding.children.remove(container)
			color = next((c for c in container.children if c.name and c.name[0] == DCMSR_DISPLAY_COLOR.value), None)
			for role in (color.children if color else []):
				role.rel = 'HAS PROPERTIES'
				finding.children.append(role)
			applied.add('f')
		elif layout == DCMSR_LAYOUT_NESTED and roles and container is None:
			for role in roles:
				finding.children.remove(role)
				role.rel = 'CONTAINS'
			color = Node(Dataset()); color.rel, color.vt, color.value = 'CONTAINS', 'CONTAINER', ('CONTAINER',)
			color.name = (DCMSR_DISPLAY_COLOR.value, 'Sonador-SR', SONADOR_SCHEME_VERSION_03); color.children = roles
			display = Node(Dataset()); display.rel, display.vt, display.value = 'HAS PROPERTIES', 'CONTAINER', ('CONTAINER',)
			display.name = (DCMSR_DISPLAY_ATTRIBUTES.value, 'Sonador-SR', SONADOR_SCHEME_VERSION_03); display.children = [color]
			finding.children.append(display); applied.add('f')
	return node, applied


class OracleMixin:
	'''	Document-level comparison of a source document and its re-save
	'''
	def assert_resave_matches(self, source, resaved, transformations):
		'''	Assert that `source` and `resaved` (datasets) hold equivalent content trees and that
			exactly `transformations` (a set of letters) were needed.
		'''
		layout = DCMSR_LAYOUT_FLAT if str(resaved.SOPClassUID) == DCMSR_SOP_CLASS_ENHANCED else DCMSR_LAYOUT_NESTED
		src_groups, out_groups = group_items(source), group_items(resaved)
		self.assertEqual(len(src_groups), len(out_groups))
		applied = set()
		for src, out in zip(src_groups, out_groups):
			expected, used = expected_group(Node(src), layout)
			applied |= used
			compare_nodes(self, expected, Node(out), 'group')
		self.assertEqual(applied, set(transformations))

		# Root: Person Observer verbatim, Device Observer the writer's, language and Image Library present
		src_person = root_items(source, codes.DCM.PersonObserverName.value)
		out_person = root_items(resaved, codes.DCM.PersonObserverName.value)
		self.assertEqual([str(i.PersonName) for i in src_person], [str(i.PersonName) for i in out_person])
		self.assert_device_observer(resaved)
		self.assertEqual(len(root_items(resaved, codes.DCM.LanguageOfContentItemAndDescendants.value)), 1)
		self.assertEqual(len(root_items(resaved, codes.DCM.ImageLibrary.value)), 1)
		self.assertEqual(set(canonical_code(i.ConceptCodeSequence[0]) for i in root_items(source, codes.DCM.ProcedureReported.value)),
			set(canonical_code(i.ConceptCodeSequence[0]) for i in root_items(resaved, codes.DCM.ProcedureReported.value)))

		# Headers outside the content tree
		self.assertEqual(str(source.SeriesInstanceUID), str(resaved.SeriesInstanceUID))
		self.assertNotEqual(str(source.SOPInstanceUID), str(resaved.SOPInstanceUID))
		self.assertEqual(str(source.get('SeriesDescription', '')), str(resaved.get('SeriesDescription', '')))
		self.assertEqual(str(source.SeriesNumber), str(resaved.SeriesNumber))
		self.assertEqual(source.CompletionFlag, resaved.CompletionFlag)
		self.assertEqual(source.VerificationFlag, resaved.VerificationFlag)
		self.assert_predecessor(resaved, source)
		self.assert_equipment(resaved)

	def assert_device_observer(self, doc):
		values = {}
		for code in (codes.DCM.DeviceObserverName, codes.DCM.DeviceObserverManufacturer, codes.DCM.DeviceObserverModelName):
			items = root_items(doc, code.value)
			self.assertEqual(len(items), 1, code.meaning)
			values[code.value] = str(items[0].TextValue)
		self.assertEqual(values, {'121013': SONADOR_IO, '121014': SONADOR_MANUFACTURER, '121015': SONADOR_IO})
		self.assertEqual(len(root_items(doc, codes.DCM.DeviceObserverUID.value)), 1)
		self.assertEqual(len(root_items(doc, codes.DCM.DeviceObserverSerialNumber.value)), 0)
		observer_type = root_items(doc, codes.DCM.ObserverType.value)
		self.assertEqual([str(i.ConceptCodeSequence[0].CodeValue) for i in observer_type], ['121007'])
		# Observer items follow the language item, the Person Observer first when present
		order = [dcm_code_value(i.ConceptNameCodeSequence[0]) for i in srdoc_children(doc)]
		self.assertEqual(order[0], '121049')
		expected = ['121005', '121012', '121013', '121014', '121015']
		if '121008' in order:
			expected = ['121008'] + expected
		self.assertEqual(order[1:1 + len(expected)], expected)

	def assert_equipment(self, doc):
		self.assertEqual((doc.Manufacturer, doc.ManufacturerModelName, doc.SoftwareVersions),
			(SONADOR_MANUFACTURER, SONADOR_IO, sonador_software_version()))

	def assert_predecessor(self, doc, previous):
		'''	The document names `previous` (the last item of its Predecessor Documents Sequence)
		'''
		refs = [(str(s.StudyInstanceUID), str(sx.SeriesInstanceUID), str(sop.ReferencedSOPInstanceUID))
			for s in doc.PredecessorDocumentsSequence for sx in s.ReferencedSeriesSequence for sop in sx.ReferencedSOPSequence]
		self.assertIn((str(previous.StudyInstanceUID), str(previous.SeriesInstanceUID), str(previous.SOPInstanceUID)), refs)
		return refs


