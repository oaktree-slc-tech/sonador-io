class PreservationTestCase(unittest.TestCase):
	'''	Unknown content stays under its parent; by-reference items parse and refuse the rewrite
	'''
	def unknown_text(self, value, relationship='HAS PROPERTIES'):
		item = Dataset(); item.RelationshipType = relationship; item.ValueType = 'TEXT'; item.TextValue = value
		item.ConceptNameCodeSequence = Sequence([srcode2dataset(Code('Sonador-Future.Attribute', 'Sonador-SR', 'A future attribute', scheme_version='9.9'))])
		return item

	def test_unknown_items_return_under_their_parent(self):
		ds = read(V1)
		group = group_items(ds)[0]
		finding = finding_item(group)
		finding.ContentSequence.append(self.unknown_text('under the finding'))
		container = named(finding.ContentSequence, DCMSR_DISPLAY_ATTRIBUTES.value)[0]
		color = named(container.ContentSequence, DCMSR_DISPLAY_COLOR.value)[0]
		color.ContentSequence.append(self.unknown_text('inside the colour container', 'CONTAINS'))
		group.ContentSequence.append(self.unknown_text('at group level', 'CONTAINS'))
		root_extra = Dataset(); root_extra.RelationshipType = 'CONTAINS'; root_extra.ValueType = 'CONTAINER'; root_extra.ContinuityOfContent = 'SEPARATE'
		root_extra.ConceptNameCodeSequence = Sequence([srcode2dataset(Code('Sonador-Future.Container', 'Sonador-SR', 'A future container', scheme_version='9.9'))])
		root_extra.ContentSequence = Sequence([self.unknown_text('inside the root container', 'CONTAINS')])
		ds.ContentSequence.append(root_extra)

		model = SonadorComprehensiveSR3D.from_sr(ds)
		finding_model = findings_of(model)[0]
		self.assertEqual([i.TextValue for i in finding_model.extra_items], ['under the finding'])
		self.assertEqual([i.TextValue for i in finding_model.display.color_extra_items], ['inside the colour container'])
		self.assertEqual(finding_model.display.extra_items, ())
		self.assertEqual([i.TextValue for i in model.groups[0].extra_items], ['at group level'])
		self.assertEqual([dcm_code_value(i.ConceptNameCodeSequence[0]) for i in model.extra_items], ['Sonador-Future.Container'])
		self.assertEqual([d.severity for d in model.diagnostics], ['info'])

		resaved = roundtrip(model.create_sr(document_template=Comprehensive3DSR))
		out_group = group_items(resaved)[0]
		out_finding = finding_item(out_group)
		self.assertEqual([c.TextValue for c in named(out_group.ContentSequence, 'Sonador-Future.Attribute')], ['at group level'])
