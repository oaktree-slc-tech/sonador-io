		series = SonadorComprehensiveSR3D.parse(doc)
		full = series.findings()
		self.assertEqual(list(full.keys()), [SYNTHETIC['SeriesInstanceUID']])
		self.assertEqual(list(full[SYNTHETIC['SeriesInstanceUID']].keys()), ['series-tag'])
		self.assertEqual(list(series.findings(series_uid=SYNTHETIC['SeriesInstanceUID']).keys()), ['series-tag'])
		self.assertEqual(list(series.findings(measurement_type='series-tag').keys()), [SYNTHETIC['SeriesInstanceUID']])
		self.assertEqual(len(series.findings('2.25.nope', 'series-tag')), 0)
		self.assertEqual(series.measurements(), OrderedDict())
		self.assertEqual(len(series.instances_collection.measurements('x', 'length')), 0)


