		self.assertEqual([c.TextValue for c in named(out_color.ContentSequence, 'Sonador-Future.Attribute')], ['inside the colour container'])
		root = named(resaved.ContentSequence, 'Sonador-Future.Container')
		self.assertEqual([c.TextValue for c in root[0].ContentSequence], ['inside the root container'])
		# The unknown items read back under the same parent
		again = SonadorComprehensiveSR3D.from_sr(resaved)
		self.assertEqual([i.TextValue for i in findings_of(again)[0].extra_items], ['under the finding'])
		self.assertEqual([i.TextValue for i in again.groups[0].extra_items], ['at group level'])

		# Enhanced SR is read and not written
		with self.assertRaises(ValueError):
			model.create_sr(document_template=EnhancedSR)

