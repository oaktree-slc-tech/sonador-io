class CodeCodecTestCase(unittest.TestCase):
	'''	Three value attributes by convention, verbatim at any length; version omitted when absent
	'''
	def test_value_attribute(self):
		self.assertEqual(dcm_code_value_attribute('img-qc.reject'), 'CodeValue')
		self.assertEqual(dcm_code_value_attribute('img-qc.metal-artifact'), 'LongCodeValue')
		self.assertEqual(dcm_code_value_attribute('urn:oid:1.2.3'), 'URNCodeValue')
		self.assertEqual(dcm_code_value_attribute('https://example.invalid/code'), 'URNCodeValue')

	def test_roundtrip(self):
		for value in ('img-qc.reject', 'img-qc.metal-artifact', 'urn:oid:1.2.3', 'x' * 80):
			for version in (None, '', '0.2'):
				ds = srcode2dataset(Code(value, 'Sonador-SEG', 'm' * 100, scheme_version=version))
				self.assertEqual(dcm_code_value(ds), value)
				self.assertEqual(sum(1 for a in ('CodeValue', 'LongCodeValue', 'URNCodeValue') if a in ds), 1)
				self.assertEqual('CodingSchemeVersion' in ds, bool(version))
				self.assertEqual(ds.CodeMeaning, 'm' * 100)
				code = dataset2srcode(ds)
				self.assertEqual((code.value, code.scheme_designator, code.meaning, code.scheme_version),
					(value, 'Sonador-SEG', 'm' * 100, version or None))

	def test_reads_any_attribute_at_any_length(self):
		for attr in ('CodeValue', 'LongCodeValue', 'URNCodeValue'):
			ds = Dataset(); setattr(ds, attr, 'a-value-of-twenty-one'); ds.CodingSchemeDesignator = 'X'; ds.CodeMeaning = 'm'
			with warnings.catch_warnings():
				warnings.simplefilter('ignore')
				self.assertEqual(dataset2srcode(ds).value, 'a-value-of-twenty-one')
			self.assertTrue(dcm_code_matches(ds, Code('a-value-of-twenty-one', 'X', 'other meaning', scheme_version='9')))
			self.assertFalse(dcm_code_matches(ds, Code('a-value-of-twenty-one', 'Y', 'm')))


