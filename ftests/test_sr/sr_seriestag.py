def roundtrip(doc):
	'''	Serialize a document and read it back (the bytes are what the other side sees)
	'''
	buf = io.BytesIO()
	doc.save_as(buf)
	buf.seek(0)
	return pydicom.dcmread(buf)


def tobytes(doc):
	buf = io.BytesIO()
	doc.save_as(buf)
	return buf.getvalue()


